func TestDocumentServiceLineMutationLifecycleAndOwnership(t *testing.T) {
	t.Run("finalized", func(t *testing.T) {
		service, repository, ctx := newLineService(t, 1)
		if err := repository.document.Finalize(time.Now().UTC()); err != nil {
			t.Fatal(err)
		}
		_, err := service.DeleteLine(ctx, repository.document.ID, repository.document.LineItems[0].ID, repository.document.Version)
		if !hasCode(err, buhari.CodeDocumentFinalized) {
			t.Fatalf("error = %v", err)
		}
	})

	t.Run("archived", func(t *testing.T) {
		service, repository, ctx := newLineService(t, 1)
		if err := repository.document.Archive(time.Now().UTC()); err != nil {
			t.Fatal(err)
		}
		_, err := service.AddLine(ctx, repository.document.ID, repository.document.Version, calculations.LineInput{Description: "Added", Quantity: 1})
		if !hasCode(err, buhari.CodeDocumentArchived) {
			t.Fatalf("error = %v", err)
		}
	})

	t.Run("stale version", func(t *testing.T) {
		service, repository, ctx := newLineService(t, 1)
		_, err := service.DeleteLine(ctx, repository.document.ID, repository.document.LineItems[0].ID, repository.document.Version+1)
		if !hasCode(err, buhari.CodeDocumentVersionConflict) {
			t.Fatalf("error = %v", err)
		}
	})

	t.Run("different owner", func(t *testing.T) {
		service, repository, _ := newLineService(t, 1)
		otherCtx := requestctx.WithExecutor(context.Background(), model.Executor{ID: model.UserID(lid.NewUser()), Role: "user"})
		_, err := service.DeleteLine(otherCtx, repository.document.ID, repository.document.LineItems[0].ID, 1)
		if !hasCode(err, buhari.CodeNotFound) {
			t.Fatalf("error = %v", err)
		}
	})
}

func TestDocumentServiceReorderLines(t *testing.T) {
	service, repository, ctx := newLineServiceWithInputs(t, []calculations.LineInput{
		{Description: "Fixed discount", Quantity: 2, UnitPriceMinor: 2_000, Discount: &calculations.Discount{Type: calculations.DiscountFixed, Value: 500}, TaxRate: 50_000},
		{Description: "Percentage discount", Quantity: 3, UnitPriceMinor: 1_000, Discount: &calculations.Discount{Type: calculations.DiscountPercentage, Value: 100_000}, TaxRate: 200_000},
		{Description: "Untaxed", Quantity: 1, UnitPriceMinor: 750},
	})
	beforeTotals := repository.document.Totals
	beforeTaxBreakdown := append([]calculations.TaxBreakdown(nil), repository.document.TaxBreakdown...)
	ids := []string{repository.document.LineItems[2].ID, repository.document.LineItems[0].ID, repository.document.LineItems[1].ID}
	result, err := service.ReorderLines(ctx, repository.document.ID, 1, ids)
	if err != nil {
		t.Fatal(err)
	}
	for index, id := range ids {
		if result.LineItems[index].ID != id {
			t.Fatalf("line %d ID=%s want=%s", index, result.LineItems[index].ID, id)
		}
	}
	if result.Version != 2 {
		t.Fatalf("version = %d", result.Version)
	}
	if result.Totals != beforeTotals {
		t.Fatalf("reorder changed totals: before=%+v after=%+v", beforeTotals, result.Totals)
	}
	if !reflect.DeepEqual(result.TaxBreakdown, beforeTaxBreakdown) {
		t.Fatalf("reorder changed tax breakdown: before=%+v after=%+v", beforeTaxBreakdown, result.TaxBreakdown)
	}
}

