func TestDocumentServiceUsesLifecycleSpecificErrors(t *testing.T) {
	t.Run("finalize already finalized", func(t *testing.T) {
		service, repository, _, ctx := newLineServiceDependencies(t, []calculations.LineInput{{Description: "Line", Quantity: 1}})
		if err := repository.document.Finalize(time.Now().UTC()); err != nil {
			t.Fatal(err)
		}
		_, err := service.Finalize(ctx, repository.document.ID, repository.document.Version)
		if !hasCode(err, buhari.CodeDocumentAlreadyFinalized) {
			t.Fatalf("finalize error = %v", err)
		}
		if repository.replaceCalls != 0 {
			t.Fatalf("finalize persisted %d times", repository.replaceCalls)
		}
	})

	t.Run("duplicate source draft", func(t *testing.T) {
		service, repository, references, ctx := newLineServiceDependencies(t, nil)
		_, err := service.Duplicate(ctx, repository.document.ID, DuplicateDocumentInput{})
		if !hasCode(err, buhari.CodeSourceDocumentNotFinalized) {
			t.Fatalf("duplicate error = %v", err)
		}
		if repository.createCalls != 0 || references.allocations != 0 {
			t.Fatalf("duplicate had side effects: creates=%d allocations=%d", repository.createCalls, references.allocations)
		}
	})
}

