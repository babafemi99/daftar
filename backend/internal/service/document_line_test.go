type lineDocumentRepository struct {
	document     model.Document
	createCalls  int
	listCalls    int
	replaceCalls int
}

var _ mercury.Documents = (*lineDocumentRepository)(nil)

func (repository *lineDocumentRepository) Create(_ context.Context, document model.Document) error {
	repository.createCalls++
	repository.document = document
	return nil
}
func (repository *lineDocumentRepository) FindByReference(context.Context, string, string) (model.Document, error) {
	return model.Document{}, buhari.New(buhari.CodeNotFound, "Document not found.")
}
func (repository *lineDocumentRepository) List(context.Context, string, mercury.DocumentListFilter) (mercury.DocumentPage, error) {
	repository.listCalls++
	return mercury.DocumentPage{}, nil
}
func (repository *lineDocumentRepository) FindByID(_ context.Context, ownerID, documentID string) (model.Document, error) {
	if ownerID != repository.document.OwnerID || documentID != repository.document.ID {
		return model.Document{}, buhari.New(buhari.CodeNotFound, "Document not found.")
	}
	return repository.document, nil
}
func (repository *lineDocumentRepository) ReplaceDraft(_ context.Context, document model.Document, expectedVersion int64) error {
	if repository.document.Version != expectedVersion {
		return buhari.New(buhari.CodeDocumentVersionConflict, "Document was changed by another request.")
	}
	repository.replaceCalls++
	repository.document = document
	return nil
}
func (repository *lineDocumentRepository) Finalize(ctx context.Context, document model.Document, version int64) error {
	return repository.ReplaceDraft(ctx, document, version)
}
func (repository *lineDocumentRepository) Archive(ctx context.Context, document model.Document, version int64) error {
	return repository.ReplaceDraft(ctx, document, version)
}
func (repository *lineDocumentRepository) Restore(ctx context.Context, document model.Document, version int64) error {
	return repository.ReplaceDraft(ctx, document, version)
}

type lineReferenceRepository struct{ allocations int }

func (repository *lineReferenceRepository) Allocate(context.Context, string, int, time.Time) (string, error) {
	repository.allocations++
	return "DOC-2026-000002", nil
}

func newLineService(t *testing.T, lineCount int) (*DocumentService, *lineDocumentRepository, context.Context) {
	t.Helper()
	lines := make([]calculations.LineInput, lineCount)
	for index := range lines {
		lines[index] = calculations.LineInput{Description: "Line", Quantity: 1, UnitPriceMinor: 1_000}
	}
	return newLineServiceWithInputs(t, lines)
}

func newLineServiceWithInputs(t *testing.T, lines []calculations.LineInput) (*DocumentService, *lineDocumentRepository, context.Context) {
	t.Helper()
	service, repository, _, ctx := newLineServiceDependencies(t, lines)
	return service, repository, ctx
}

func newLineServiceDependencies(t *testing.T, lines []calculations.LineInput) (*DocumentService, *lineDocumentRepository, *lineReferenceRepository, context.Context) {
	t.Helper()
	ownerID := lid.NewUser()
	document, err := model.NewDocument(ownerID, "DOC-2026-000001", model.DocumentInput{
		Title: "Line service", Customer: "Acme Limited",
		IssueDate: time.Date(2026, 8, 8, 0, 0, 0, 0, time.UTC), Currency: model.CurrencyUSD, LineItems: lines,
	}, time.Date(2026, 8, 8, 10, 0, 0, 0, time.UTC))
	if err != nil {
		t.Fatal(err)
	}
	repository := &lineDocumentRepository{document: document}
	references := &lineReferenceRepository{}
	service, err := NewDocumentService(repository, references)
	if err != nil {
		t.Fatal(err)
	}
	ctx := requestctx.WithExecutor(context.Background(), model.Executor{ID: model.UserID(ownerID), Role: "user"})
	return service, repository, references, ctx
}
